#!/usr/bin/env node
/**
 * Regenerate src/acp-shim-source.ts from src/acp-shim.mjs.
 * The plugin's host bundle is a single host.mjs — sidecar files do not ship,
 * so the shim travels inside the bundle as base64 and is materialized into
 * the provider dataDir at bridge start. Run this after editing the shim:
 *
 *   node scripts/gen-acp-shim-source.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shim = readFileSync(join(here, "..", "src", "acp-shim.mjs"));
const b64 = shim.toString("base64");
writeFileSync(
  join(here, "..", "src", "acp-shim-source.ts"),
  `/** GENERATED by scripts/gen-acp-shim-source.mjs — do not edit by hand. */\n` +
    `export const ACP_SHIM_SOURCE_B64 = "${b64}";\n`,
);
console.log(`acp-shim-source.ts written (${shim.length} bytes)`);
