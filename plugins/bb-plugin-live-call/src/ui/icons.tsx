/** Иконка карточки действия по имени инструмента. */
export function toolIcon(tool: string, cls: string): IconName {
  switch (tool) {
    case "bb_overview":
      return "eye";
    case "list_threads":
    case "search_memory":
      return "search";
    case "read_thread":
      return "book";
    case "list_pending":
      return "bell";
    case "watch_thread":
      return "eye";
    case "send_to_thread":
      return "send";
    case "answer_interaction":
      return cls === "P" ? "shield" : "message";
    case "stop_thread":
      return "square";
    case "start_thread":
    case "tasks_dispatch":
      return "rocket";
    case "tasks_create":
      return "list";
    case "switch_mode":
      return "zap";
    case "end_call":
      return "phone-off";
    default:
      return "zap";
  }
}
