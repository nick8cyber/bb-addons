export interface ThreadPromptContext {
  thread: {
    id: string;
    title: string;
    project?: string;
    state?: string;
    providerId?: string;
    model?: string;
  };
  nowUtc: string;
  threadState: {
    status: string; // работает / ждёт тебя / ошибка / свободен
    lastMessageTime?: string;
    lastOwnerMessageIndex?: number;
    lastAgentMessageIndex?: number;
  };
  messagesBlock: string;
  memory: string[];
  brainSummary?: string;
  /** Мозговой центр есть в этом звонке (git-окружение). false — не упоминать сводку (живой звонок 03.11). */
  brainAvailable?: boolean;
  /** §15.4 п. 7: доступные ручки проекта в звонке по треду. */
  projectToolsLine?: string;
}

