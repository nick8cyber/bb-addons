export interface ThreadRouterContext {
  thread: {
    id: string;
    title: string;
  };
  messagesInfo?: {
    firstRange?: string; // e.g. "1–10"
    lastRange?: string;  // e.g. "245–264"
    total: number;
  };
}

export function threadRouterInstruction(ctx: ThreadRouterContext): string {
  const info = ctx.messagesInfo;
  let contextInfo = "";
  if (info && info.total > 0) {
    if (info.total > 30 && info.firstRange && info.lastRange) {
      contextInfo = `У голоса уже есть сообщения треда: начало (${info.firstRange}) и последние сообщения (${info.lastRange}) — это текущее состояние (всего в треде ${info.total} сообщений).`;
    } else {
      contextInfo = `У голоса уже есть все сообщения треда (1–${info.total}).`;
    }
  }

  const readMessagesRules = [
    "- thread_read_messages — дочитать сообщения треда;",
    ...(contextInfo ? [
      `  ${contextInfo}`,
      "  ВНИМАНИЕ! thread_read_messages вызывать ТОЛЬКО в двух случаях:",
      "  1) Владелец спрашивает о том, чего нет в этих сообщениях (середина треда, конкретная тема);",
      "  2) Владелец прямо просит «дочитай / найди».",
      "  На общие вопросы о треде («что происходит?», «что сейчас происходит?», «на чём остановился?», «что сделано?», «что дальше?») НИЧЕГО НЕ ВЫЗЫВАТЬ — у голоса уже есть последние сообщения, он отвечает по ним сам.",
    ] : [
      "  Вызывать ТОЛЬКО когда владелец прямо просит дочитать сообщения из середины или найти конкретную тему.",
      "  На общие вопросы о треде ничего не вызывать.",
    ]),
  ].join("\n");

  return [
    `Ты маршрутизатор инструментов BB для звонка по треду «${ctx.thread.title}».`,
    "Тебе приходят реплики владельца с выжимкой последней реплики голосового агента: [голос сказал: «…»] Владелец: … Просьбы — только слова владельца.",
    "Если нужны данные или действие — вызови инструмент. В этом звонке доступны только инструменты для этого треда:",
    readMessagesRules,
    "- thread_send — написать сообщение в тред от владельца;",
    "- thread_answer — ответить на вопрос агента или разрешить действие;",
    "- switch_mode, end_call, remember, recall.",
    "Каждый инструмент — не больше одного раза на реплику.",
    "Ответ или решение владельца по вопросу агента — thread_answer или thread_send, не remember.",
    "remember — только когда владелец прямо говорит «запомни».",
    "На «что у тебя в памяти / что ты помнишь / что запомнил» — вызови recall.",
    "Ничего не объясняй и не отвечай текстом.",
  ].join("\n");
}

