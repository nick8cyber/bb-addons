#!/usr/bin/env node
/**
 * Собирает src/vendor/acp-bridge.js: копия ACP-моста из @get-bb/plugin-sdk
 * плюс диалект Devin (субагенты Devin -> элементы `delegation` bb, как у Cursor).
 *
 * Зачем копия: реестр диалектов в SDK не публичный (DIALECTS_BY_ID внутри
 * модуля), добавить диалект снаружи нельзя. Копия живёт в нашем плагине,
 * поэтому обновления bb её не трогают. После обновления SDK в package.json —
 * перезапустить `npm run vendor`: скрипт падает, если якоря в SDK поменялись.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const sdkPkg = join(root, "node_modules", "@get-bb", "plugin-sdk", "package.json");
const sdkVersion = JSON.parse(readFileSync(sdkPkg, "utf8")).version;
const src = join(dirname(sdkPkg), "dist", "provider-bridge-acp.js");
let code = readFileSync(src, "utf8");
const dialect = readFileSync(join(root, "src", "devin-dialect.js"), "utf8");

function replaceOnce(anchor, replacement) {
  const count = code.split(anchor).length - 1;
  if (count !== 1) {
    throw new Error(`anchor found ${count} times (need 1): ${anchor.slice(0, 80)}`);
  }
  code = code.replace(anchor, replacement);
}

replaceOnce(
  "var DIALECTS_BY_ID = /* @__PURE__ */ new Map([\n",
  `${dialect}\nvar DIALECTS_BY_ID = /* @__PURE__ */ new Map([\n  [DEVIN_ACP_DIALECT.id, DEVIN_ACP_DIALECT],\n`,
);
replaceOnce(
  "var DIALECT_IDS_BY_COMMAND = {\n",
  "var DIALECT_IDS_BY_COMMAND = {\n  devin: DEVIN_ACP_DIALECT.id,\n",
);
// Правила bb треда сохраняются в файл при создании ACP-сессии (новой и восстановленной).
replaceOnce(
  "  session = {\n    bbThreadId,\n    construction: params,\n",
  "  persistDevinBbInstructions(bbThreadId, params.instructions);\n  session = {\n    bbThreadId,\n    construction: params,\n",
);
// devin-dialect.js пользуется модулями, которые мост уже импортирует под этими именами.
for (const imp of ['import fs from "node:fs/promises";', 'import os from "node:os";', 'import path2 from "node:path";']) {
  if (!code.includes(imp)) {
    throw new Error(`SDK bridge no longer has: ${imp}`);
  }
}
// Тот же контракт, что у delegationPresentation, должен существовать в SDK.
if (!code.includes("function delegationPresentation(args)")) {
  throw new Error("delegationPresentation() not found in SDK bridge");
}

const out = join(root, "src", "vendor", "acp-bridge.js");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// @ts-nocheck\n// GENERATED by scripts/vendor-acp-bridge.mjs from @get-bb/plugin-sdk@${sdkVersion}` +
    ` dist/provider-bridge-acp.js + src/devin-dialect.js. Do not edit.\n${code}`,
);
console.log(`vendored ACP bridge from plugin-sdk@${sdkVersion} -> ${out}`);
